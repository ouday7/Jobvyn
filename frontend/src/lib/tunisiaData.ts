// دالة إرجاع أيقونة الاختصاص
export const getSpecialtyIcon = (specialty: string): string => {
  if (!specialty) return "🔧";
  
  // مطابقة تامة
  for (const item of specialtiesList) {
    if (item.name === specialty) return item.icon;
  }
  
  // مطابقة جزئية
  const s = specialty.toLowerCase();
  if (s.includes("ممرض")) return "💉";
  if (s.includes("طبيب")) return "🏥";
  if (s.includes("مهندس") || s.includes("فلاح")) return "🌾";
  if (s.includes("نجار")) return "🪵";
  if (s.includes("حداد")) return "🔩";
  if (s.includes("كهرب")) return "⚡";
  if (s.includes("سباك") || s.includes("بلومبي")) return "🚰";
  if (s.includes("بناء")) return "🧱";
  if (s.includes("دهان")) return "🎨";
  if (s.includes("خياط")) return "🧵";
  if (s.includes("كوافير")) return "💇";
  if (s.includes("طباخ")) return "🍳";
  if (s.includes("ميكانيكي")) return "🔧";
  if (s.includes("سائق")) return "🚗";
  if (s.includes("أستاذ") || s.includes("معلم")) return "📚";
  if (s.includes("مطور") || s.includes("مبرمج")) return "💻";
  if (s.includes("محاسب")) return "🧮";
  if (s.includes("محامي")) return "⚖️";
  
  return "🔧";
};

